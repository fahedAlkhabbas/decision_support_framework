"""
Validation Manager: independently re-checks a deployment against every
requirement.

The checks below do not use the solver model: they recompute every
requirement from the assignment, the scenario (knowledge base) and the
infrastructure. A deployment is accepted only if no violation is found. The
same checker is used in the ablation study to count which requirements a
deployment computed *without* a constraint family violates.
"""

from collections import defaultdict

from constraints.constraint_manager import FAMILIES
from core.metrics import hop_delay, flow_delays, NO_LINK_LATENCY


class ValidationManager:
    """
    Verifies that the topologies generated by the Solution Manager satisfy all
    specified system- and microservice-level requirements, and filters out
    infeasible topologies.
    """

    def __init__(self, knowledge_base=None):
        self.kb = knowledge_base

    # ------------------------------------------------------------------ #
    def verify_deployment(self, assignment, nodes, caps, comm, system_nfrs, kb=None):
        """
        Check a deployment against all requirement families.

        Args:
            assignment: {service: [node, ...]}

        Returns:
            list of (family, message) violations (empty if the deployment is valid)
        """
        kb = kb or self.kb
        v = []
        comps = kb.components
        req = kb.comp_requirements
        nfrs = system_nfrs
        max_delay = nfrs["performance"]["max_delay"]
        min_tp = nfrs["performance"]["min_throughput"]

        # placement (always required)
        for c in comps:
            if not assignment.get(c):
                v.append(("placement", f"{c} is not deployed"))
            for n in assignment.get(c, []):
                if n not in caps:
                    v.append(("placement", f"{c} assigned to unknown node {n}"))
        if any(f == "placement" for f, _ in v):
            return v

        # replication / availability
        rep = kb.replicas_for(nfrs["availability"])
        for c in comps:
            if len(assignment[c]) != rep:
                v.append(("replication", f"{c} has {len(assignment[c])} replicas, {rep} required "
                                         f"for availability {nfrs['availability']}%"))

        # node-local requirements
        load = defaultdict(lambda: defaultdict(int))
        for c in comps:
            cd = req[c]
            for n in assignment[c]:
                cap = caps[n]
                load[n]["cpu"] += cd["cpu"]
                load[n]["memory"] += cd["memory"]
                load[n]["throughput"] += cd.get("throughput", 0)
                if cap["proc_delay"] > cd["response_time"]:
                    v.append(("ms_response_time", f"{c}@{n}: node delay {cap['proc_delay']} ms > "
                                                  f"required response time {cd['response_time']} ms"))
                if cd["response_time"] > max_delay:
                    v.append(("ms_response_time", f"{c}: response time {cd['response_time']} ms > "
                                                  f"system max delay {max_delay} ms"))
                if "mtbf" in cd and cap["mtbf"] < cd["mtbf"]:
                    v.append(("ms_mtbf", f"{c}@{n}: MTBF {cap['mtbf']} h < {cd['mtbf']} h"))
                if "encryption_compliance" in cd and \
                        cap["encryption_compliance"] < cd["encryption_compliance"]:
                    v.append(("ms_encryption", f"{c}@{n}: encryption {cap['encryption_compliance']} "
                                               f"< {cd['encryption_compliance']}"))
                allowed = kb.privacy_compatibility[cd.get("privacy", "low")]
                if cap["privacy_capability"] not in allowed:
                    v.append(("privacy", f"{c}@{n}: node privacy '{cap['privacy_capability']}' "
                                         f"incompatible with '{cd.get('privacy', 'low')}'"))
        for n, l in load.items():
            if l["cpu"] > caps[n]["cpu"]:
                v.append(("capacity", f"{n}: CPU {l['cpu']} > {caps[n]['cpu']}"))
            if l["memory"] > caps[n]["memory"]:
                v.append(("capacity", f"{n}: memory {l['memory']} > {caps[n]['memory']}"))
            if l["throughput"] > caps[n].get("throughput_cap", 10 ** 9):
                v.append(("throughput_capacity", f"{n}: load {l['throughput']} events/s > "
                                                 f"{caps[n]['throughput_cap']}"))
            if caps[n]["encryption_compliance"] < nfrs["security"]:
                v.append(("system_security", f"{n}: encryption {caps[n]['encryption_compliance']} < "
                                             f"system level {nfrs['security']}"))

        # system minimum throughput of services in flows
        for chain in kb.dataflow_paths.values():
            for c in chain:
                if req[c].get("throughput", min_tp) < min_tp:
                    v.append(("min_throughput", f"{c}: {req[c]['throughput']} events/s < {min_tp}"))

        # hop latency SLAs (every replica pair; co-located pairs cost 2 * processing delay)
        for (c1, c2), max_lat in kb.latency_constraints.items():
            for n1 in assignment[c1]:
                for n2 in assignment[c2]:
                    d = hop_delay(caps, comm, n1, n2)
                    if d > max_lat:
                        what = "no link" if (n1, n2) not in comm else f"{d} ms"
                        v.append(("hop_latency", f"{c1}@{n1} -> {c2}@{n2}: {what} > SLA {max_lat} ms"))

        # bandwidth on flow hops
        required_bw = kb.required_bandwidth(nfrs)
        seen = set()
        for _, c1, c2 in kb.flow_hops():
            if (c1, c2) in seen:
                continue
            seen.add((c1, c2))
            for n1 in assignment[c1]:
                for n2 in assignment[c2]:
                    if n1 == n2:
                        continue
                    bw = comm.get((n1, n2), {}).get("bandwidth", 0)
                    if bw < required_bw:
                        v.append(("hop_bandwidth", f"{c1}@{n1} -> {c2}@{n2}: {bw} Mbps < "
                                                   f"{required_bw:g} Mbps"))

        # end-to-end delay of flows
        for fname, d in flow_delays(kb, caps, comm, assignment).items():
            if d > max_delay:
                v.append(("e2e_delay", f"flow {fname}: {d if d < NO_LINK_LATENCY else 'unlinked'} ms "
                                       f"> {max_delay} ms"))
        return v

    @staticmethod
    def violations_by_family(violations):
        counts = {f: 0 for f in ["placement"] + FAMILIES}
        for fam, _ in violations:
            counts[fam] = counts.get(fam, 0) + 1
        return counts

    def verify_topologies(self, result, nodes, caps, comm, system_nfrs):
        """
        Re-check a SolveResult. Returns (is_valid, message, violations).
        """
        if not result.ok:
            return False, f"No feasible deployment found (solver status {result.status})", []
        violations = self.verify_deployment(result.assignment, nodes, caps, comm, system_nfrs)
        if violations:
            return False, f"{len(violations)} requirement violation(s)", violations
        return True, "Topology verified successfully against all requirements", []
